"""
HAR Monitor home page, generated in Python (Group EIC-16).

FastAPI serves this page at  /  (see app.py). Python builds:
  * the pipeline diagram (online path every 2.56 s + offline training path), from the
    PIPELINE / DECISION / training_steps definitions in live_page.py
  * the headline numbers (test accuracy, test windows, best validation, features),
    read from model/metrics.json so they always match the deployed model
The live prediction section on the same page is then fed by /api/stream every 2.56 s,
which is answered by the same Python model.

Everything the browser needs (markup, styles and the small browser script that keeps
the live section updating) is stored in this Python file and sent by FastAPI, so the
website has no separate HTML, CSS or JavaScript files.
"""
from __future__ import annotations

import html
from typing import Callable

from fastapi import APIRouter
from fastapi.responses import HTMLResponse

from live_page import DECISION, PIPELINE, training_steps

e = html.escape


def _step(s: dict, number: int | None) -> str:
    num = f'<span class="num">{number}</span>' if number else ""
    tag = f'<p class="tag">{e(s["tag"])}</p>' if s.get("tag") else ""
    cls = "step hi" if s.get("highlight") else "step"
    return f'<li class="{cls}">{num}{tag}<h3>{e(s["title"])}</h3><p class="note">{e(s["text"])}</p></li>'


def pipeline_section(metrics: dict, threshold: float) -> str:
    online = "\n          ".join(_step(s, i + 1) for i, s in enumerate(PIPELINE))
    offline = "\n          ".join(_step(s, None) for s in training_steps(metrics))
    yes_t, yes_d = DECISION["yes"]
    no_t, no_d = DECISION["no"]
    q = DECISION["question"].format(threshold=threshold)
    return f"""  <!-- PIPELINE (generated by main_page.py) -->
  <section class="sec white" id="pipeline">
    <div class="wrap">
      <div class="head">
        <div><p class="lab">How it works · Pipeline</p><h2>From wearable sensor<br>to <em>factory response</em></h2></div>
        <p class="body">The model is trained once, offline, on the UCI HAR data. In use, every 2.56-second window from a worker's sensor goes through the online path below and ends in a safety decision. Watch it run in the live prediction section further down.</p>
      </div>
      <div class="lane">
        <p class="lab lane-t"><span class="lane-dot"></span>Online · every 2.56 s</p>
        <ol class="flow">
          {online}
        </ol>
        <div class="decide">
          <div class="gate-q"><span class="num">{len(PIPELINE) + 1}</span><div><p class="tag">Decision</p><h3>{e(q)}</h3></div></div>
          <div class="branches">
            <div class="br yes"><p class="lab">Yes · automatic</p><h3>{e(yes_t)}</h3><p class="note">{e(yes_d)}</p></div>
            <div class="br no"><p class="lab">No · human check</p><h3>{e(no_t)}</h3><p class="note">{e(no_d)}</p></div>
          </div>
        </div>
      </div>
      <div class="lane off">
        <p class="lab lane-t"><span class="lane-dot"></span>Offline · training, done once</p>
        <ol class="flow small">
          {offline}
        </ol>
      </div>
    </div>
  </section>"""


def headline_numbers(m: dict) -> dict:
    """Server-side values for the four stat cards (the browser refreshes them from /api/metrics)."""
    k, d, rf = m.get("keras", {}), m.get("dataset", {}), m.get("random_forest", {})
    pct = lambda v: f"{v * 100:.1f}%" if isinstance(v, (int, float)) else "–"
    return {
        "ACC": pct(k.get("test_accuracy")),
        "ACC_S": (f"Keras Dense v1. Random Forest scores {pct(rf['test_accuracy'])} on the same split."
                  if "test_accuracy" in rf else "Keras Dense v1 on held-out subjects."),
        "TEST": f"{d['test_windows']:,}" if "test_windows" in d else "–",
        "TEST_S": f"From {d.get('test_subjects', 9)} subjects the model never saw during training.",
        "VAL": pct(k.get("val_accuracy")),
        "VAL_S": (f"Epoch {k['best_epoch']}, subject-wise validation. Early stopping restored this epoch."
                  if "best_epoch" in k else "Subject-wise validation."),
        "FEAT": str(d.get("features", 561)),
    }


def render_home(metrics: dict, threshold: float, group: str) -> str:
    page = TEMPLATE.replace("{{PIPELINE}}", pipeline_section(metrics, threshold))
    for key, value in headline_numbers(metrics).items():
        page = page.replace("{{" + key + "}}", e(value))
    page = page.replace("{{GROUP}}", e(group))
    # styles and browser script are inserted last so their text is never altered
    return page.replace("{{STYLE}}", STYLE).replace("{{SCRIPT}}", SCRIPT)


def create_router(get_metrics: Callable, threshold: float = 0.7, group: str = "EIC-16") -> APIRouter:
    router = APIRouter()

    @router.get("/", response_class=HTMLResponse, include_in_schema=False)
    @router.get("/index.html", response_class=HTMLResponse, include_in_schema=False)
    def home():
        try:
            metrics = get_metrics()
        except Exception:
            metrics = {}          # page still renders; the browser shows a message if the API is down
        return HTMLResponse(render_home(metrics, threshold, group), headers={"Cache-Control": "no-store"})

    return router


